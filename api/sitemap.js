/**
 * Consolidated Sitemap API — single source of truth.
 *
 * /sitemap.xml (declared in robots.txt) is the canonical sitemap. The Vercel
 * rewrite routes it here; /sitemap-complete.xml now 301-redirects to
 * /sitemap.xml at the Vercel rewrite layer — no more two endpoints with
 * near-identical payloads.
 *
 * Content-page URLs (industries, our-work, about, contact, education,
 * legal-notice, privacy-policy, …) are pulled LIVE from content_pages instead
 * of a hardcoded array. Every time a new slug or language row is published,
 * the sitemap picks it up on the next regeneration. A regression guard logs
 * an error if the count of emitted content-page URLs drops below the count
 * of published rows in content_pages — that's how the previous 42-URL gap
 * went silent for months.
 *
 * Storage-first: on each request we try Supabase Storage's sitemap-complete
 * blob (regenerated by the generate-sitemap Edge Function on cron). Only if
 * Storage is unavailable do we build a fresh sitemap on the fly here.
 *
 * Other routes handled via ?type: index, lang.
 */

