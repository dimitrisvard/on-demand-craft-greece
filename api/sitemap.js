function buildPageUrl(lang, page) {
  const s = SLUGS[lang];
  const pagePath = page.path(s);
  return encodeSitemapUrl(BASE_URL + '/' + lang + pagePath);
}

function buildStaticPageHreflang(page) {
  const links = LANGUAGES.map(lang => {
    const url = escapeXml(buildPageUrl(lang, page));
    return '    <xhtml:link rel="alternate" hreflang="' + lang + '" href="' + url + '"/>';
  });
  const englishUrl = escapeXml(buildPageUrl('en', page));
  links.push('    <xhtml:link rel="alternate" hreflang="x-default" href="' + englishUrl + '"/>');
  return links.join('\n');
}

function buildStaticUrlEntry(lang, page, today) {
  const loc = escapeXml(buildPageUrl(lang, page));
  // sitemaps.org XSD: <loc>/<lastmod>/<changefreq>/<priority> first, then
  // xhtml:link extensions. Reversing this trips GSC's strict validator.
  return '  <url>\n    <loc>' + loc + '</loc>\n    <lastmod>' + today + '</lastmod>\n    <changefreq>' + page.changefreq + '</changefreq>\n    <priority>' + page.priority + '</priority>\n' + buildStaticPageHreflang(page) + '\n  </url>';
}

function buildContentPageUrl(lang, row) {
  const segment = row.localized_slug || row.slug;
  return encodeSitemapUrl(BASE_URL + '/' + lang + '/' + segment);
}

function buildContentPageHreflang(slugGroup) {
  const links = [];
  for (const lang of LANGUAGES) {
    const row = slugGroup.get(lang);
    if (!row) continue;
    const url = escapeXml(buildContentPageUrl(lang, row));
    links.push('    <xhtml:link rel="alternate" hreflang="' + lang + '" href="' + url + '"/>');
  }
  const enRow = slugGroup.get('en') || slugGroup.values().next().value;
  if (enRow) {
    const defaultLang = slugGroup.has('en') ? 'en' : [...slugGroup.keys()][0];
    const url = escapeXml(buildContentPageUrl(defaultLang, enRow));
    links.push('    <xhtml:link rel="alternate" hreflang="x-default" href="' + url + '"/>');
  }
  return links.join('\n');
}

function buildContentPageUrlEntry(lang, row, slugGroup, today) {
  const loc = escapeXml(buildContentPageUrl(lang, row));
  const meta = CONTENT_PAGE_META[row.slug] || { priority: '0.6', changefreq: 'monthly' };
  const lastmod = row.updated_at ? String(row.updated_at).split('T')[0] : today;
  return '  <url>\n    <loc>' + loc + '</loc>\n    <lastmod>' + lastmod + '</lastmod>\n    <changefreq>' + meta.changefreq + '</changefreq>\n    <priority>' + meta.priority + '</priority>\n' + buildContentPageHreflang(slugGroup) + '\n  </url>';
}

function buildBlogHreflang(article, siblings) {
  const links = siblings.map(sibling => {
    const lang = (sibling.language || 'en').trim().toLowerCase();
    const blogSlug = SLUGS[lang]?.blog || 'blog';
    const url = escapeXml(encodeSitemapUrl(BASE_URL + '/' + lang + '/' + blogSlug + '/' + sibling.slug));
    return '    <xhtml:link rel="alternate" hreflang="' + lang + '" href="' + url + '"/>';
  });
  const englishSibling = siblings.find(s => (s.language || '').trim().toLowerCase() === 'en');
  if (englishSibling) {
    const url = escapeXml(encodeSitemapUrl(BASE_URL + '/en/' + SLUGS.en.blog + '/' + englishSibling.slug));
    links.push('    <xhtml:link rel="alternate" hreflang="x-default" href="' + url + '"/>');
  }
  return links.join('\n');
}

function buildBlogUrlEntry(article, siblings, today) {
  const lang = (article.language || 'en').trim().toLowerCase();
  const blogSlug = SLUGS[lang]?.blog || 'blog';
  const loc = escapeXml(encodeSitemapUrl(BASE_URL + '/' + lang + '/' + blogSlug + '/' + article.slug));
  const lastmod = (article.updated_at || article.created_at || today).split('T')[0];
  const hreflang = siblings.length > 1 ? '\n' + buildBlogHreflang(article, siblings) : '';
  return '  <url>\n    <loc>' + loc + '</loc>\n    <lastmod>' + lastmod + '</lastmod>\n    <changefreq>weekly</changefreq>\n    <priority>0.6</priority>' + hreflang + '\n  </url>';
}

async function fetchBlogArticles() {
  const SUPABASE_ANON_KEY = process.env.SUPABASE_ANON_KEY || '';
  if (!SUPABASE_ANON_KEY) {
    console.warn('[sitemap] SUPABASE_ANON_KEY not set');
    return [];
  }
  try {
    const response = await fetch(
      SUPABASE_URL + '/rest/v1/articles?select=slug,language,updated_at,created_at,translation_id&status=eq.published&order=created_at.desc',
      { headers: { 'apikey': SUPABASE_ANON_KEY, 'Authorization': 'Bearer ' + SUPABASE_ANON_KEY } }
    );
    if (!response.ok) return [];
    const articles = await response.json();
    return Array.isArray(articles) ? articles : [];
  } catch (error) {
    console.error('[sitemap] Error fetching articles:', error);
    return [];
  }
}

async function fetchContentPages() {
  const SUPABASE_ANON_KEY = process.env.SUPABASE_ANON_KEY || '';
  if (!SUPABASE_ANON_KEY) {
    console.warn('[sitemap] SUPABASE_ANON_KEY not set');
    return [];
  }
  try {
    // Pull every published content_pages row in a single round trip. 'home'
    // is excluded because it's rendered as bare /:lang/ via STATIC_PAGES;
    // 'blog' is excluded because the blog INDEX has its own STATIC_PAGES
    // entry and individual blog articles come from fetchBlogArticles().
    const response = await fetch(
      SUPABASE_URL + '/rest/v1/content_pages?select=language,slug,localized_slug,updated_at&status=eq.published&slug=not.in.(home,blog)&order=slug,language',
      { headers: { 'apikey': SUPABASE_ANON_KEY, 'Authorization': 'Bearer ' + SUPABASE_ANON_KEY } }
    );
    if (!response.ok) return [];
    const rows = await response.json();
    return Array.isArray(rows) ? rows : [];
  } catch (error) {
    console.error('[sitemap] Error fetching content_pages:', error);
    return [];
  }
}

function groupContentPagesByCanonicalSlug(rows) {
  const groups = new Map();
  for (const row of rows) {
    const lang = (row.language || '').trim().toLowerCase();
    if (!LANGUAGES.includes(lang)) continue;
    if (!groups.has(row.slug)) groups.set(row.slug, new Map());
    groups.get(row.slug).set(lang, row);
  }
  return groups;
}

// ─── Main sitemap (with hreflang, blog entries, storage fallback) ───
async function handleMain(req, res) {
  try {
    const storageResponse = await fetch(STORAGE_URL);
    if (storageResponse.ok) {
      const xml = await storageResponse.text();
      if (xml && xml.includes('<urlset') && xml.length > 100) {
        return res.status(200).send(xml);
      }
    }
  } catch (e) {
    console.warn('[sitemap] Storage fetch failed, falling back to dynamic generation:', e.message);
  }

  try {
    const today = new Date().toISOString().split('T')[0];

    // Fetch blog + content_pages in parallel so cold-start cost is one RTT.
    const [articles, contentPages] = await Promise.all([
      fetchBlogArticles(),
      fetchContentPages(),
    ]);

    const staticEntries = [];
    for (const page of STATIC_PAGES) {
      for (const lang of LANGUAGES) {
        staticEntries.push(buildStaticUrlEntry(lang, page, today));
      }
    }

    const contentGroups = groupContentPagesByCanonicalSlug(contentPages);
    const contentEntries = [];
    let contentUrlCount = 0;
    for (const [, slugGroup] of contentGroups) {
      for (const [lang, row] of slugGroup) {
        contentEntries.push(buildContentPageUrlEntry(lang, row, slugGroup, today));
        contentUrlCount++;
      }
    }

    // Regression guard: every published content_pages row must appear in the
    // sitemap. If emission count falls below DB count, log a loud error so
    // this gap doesn't go silent for another three months.
    if (contentUrlCount < contentPages.length) {
      console.error(
        '[sitemap] Regression guard tripped: emitted ' + contentUrlCount +
        ' content-page URLs but content_pages has ' + contentPages.length +
        ' published rows. Missing rows likely have an unsupported language.'
      );
    }

    const translationGroups = new Map();
    const orphanArticles = [];
    for (const article of articles) {
      const normalizedLang = (article.language || '').trim().toLowerCase();
      if (!LANGUAGES.includes(normalizedLang)) continue;
      if (article.translation_id) {
        if (!translationGroups.has(article.translation_id)) translationGroups.set(article.translation_id, []);
        translationGroups.get(article.translation_id).push(article);
      } else {
        orphanArticles.push(article);
      }
    }

    const blogEntries = [];
    for (const [, siblings] of translationGroups) {
      for (const article of siblings) blogEntries.push(buildBlogUrlEntry(article, siblings, today));
    }
    for (const article of orphanArticles) blogEntries.push(buildBlogUrlEntry(article, [article], today));

    const xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' +
      staticEntries.join('\n') + '\n' +
      contentEntries.join('\n') + '\n' +
      blogEntries.join('\n') + '\n</urlset>';
    res.status(200).send(xml);
  } catch (error) {
    console.error('[sitemap] Error generating sitemap:', error);
    res.status(500).send('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"/>');
  }
}

// ─── Sitemap index ───
async function handleIndex(req, res) {
  try {
    const sitemapUrl = SUPABASE_URL + '/storage/v1/object/public/sitemaps/sitemap-index.xml';
    const response = await fetch(sitemapUrl, { headers: { 'Accept': 'application/xml' } });
    if (!response.ok) {
      console.error('Failed to fetch sitemap-index: ' + response.status + ' ' + response.statusText);
      return res.status(200).send('<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</sitemapindex>');
    }
    const xml = await response.text();
    res.status(200).send(xml);
  } catch (error) {
    console.error('Error serving sitemap-index:', error);
    res.status(200).send('<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</sitemapindex>');
  }
}

// ─── Language-specific sitemap ───
async function handleLang(req, res) {
  const url = req.url || '';
  const match = url.match(/lang=([a-z]{2})/i);
  const lang = match ? match[1].toLowerCase() : 'en';

  if (!LANGUAGES.includes(lang)) {
    return res.status(404).send('Sitemap not found');
  }

  try {
    const sitemapUrl = SUPABASE_URL + '/storage/v1/object/public/sitemaps/sitemap-' + lang + '.xml';
    const response = await fetch(sitemapUrl, { headers: { 'Accept': 'application/xml' } });
    if (!response.ok) {
      console.error('Failed to fetch sitemap-' + lang + ': ' + response.status + ' ' + response.statusText);
      return res.status(404).send('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</urlset>');
    }
    const xml = await response.text();
    res.status(200).send(xml);
  } catch (error) {
    console.error('Error serving sitemap-' + lang + ':', error);
    res.status(404).send('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</urlset>');
  }
}

// ─── Sitemap-index pointing at /sitemap-complete.xml ────────────────────────
// /sitemap.xml is served as a tiny <sitemapindex> that references the full
// urlset at /sitemap-complete.xml. Why we shape it this way:
//
//   • GSC has been holding a stale "could not be read" verdict on /sitemap.xml
//     even though every wire-level probe shows it serves byte-identical XML
//     to /sitemap-complete.xml (which IS accepted). Returning a different
//     XML root element (`<sitemapindex>` instead of `<urlset>`) gives GSC's
//     parser a freshly-shaped document to validate, which in practice clears
//     the kind of submission-database error that survives manual re-submits.
//
//   • Sitemap-protocol-correct: an index that lists `/sitemap-complete.xml`
//     is exactly how google.com/webmasters/answer/183668 says to publish
//     multi-file or future-splittable sitemaps. The index → urlset chain is
//     resolved by every crawler.
//
//   • robots.txt continues advertising /sitemap.xml; Googlebot follows the
//     index to /sitemap-complete.xml on its own.
//
//   • /sitemap-complete.xml is unchanged — still served by handleMain as the
//     full urlset; existing GSC submissions for it stay valid.
function handleMainIndex(_req, res) {
  const today = new Date().toISOString().split('T')[0];
  const completeUrl = encodeSitemapUrl(BASE_URL + '/sitemap-complete.xml');
  const xml =
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    '  <sitemap>\n' +
    '    <loc>' + escapeXml(completeUrl) + '</loc>\n' +
    '    <lastmod>' + today + '</lastmod>\n' +
    '  </sitemap>\n' +
    '</sitemapindex>\n';
  res.status(200).send(xml);
}

export default async function handler(req, res) {
  res.setHeader('Content-Type', 'application/xml; charset=utf-8');
  res.setHeader('Cache-Control', 'public, max-age=3600, s-maxage=3600');
  // Tell intermediaries the response varies by Accept-Encoding so CDN
  // caches don't mix gzip/br/identity bodies.
  res.setHeader('Vary', 'Accept-Encoding');

  const urlObj = new URL(req.url, 'http://localhost');
  const type = urlObj.searchParams.get('type');

  // Routing summary (vercel.json rewrites):
  //   /sitemap.xml          → ?type=main-index → handleMainIndex — sitemapindex pointing to /sitemap-complete.xml
  //   /sitemap-complete.xml → no query → handleMain — full urlset
  //   /sitemap-index.xml    → ?type=index      → legacy storage-backed index
  //   /sitemap-:lang.xml    → ?type=lang       → per-language storage blob
  // /sitemap.xml serves a tiny <sitemapindex> pointing to /sitemap-complete.xml
  if (type === 'main-index') return handleMainIndex(req, res);
  if (type === 'index') return handleIndex(req, res);
  if (type === 'lang') return handleLang(req, res);
  return handleMain(req, res);
}
